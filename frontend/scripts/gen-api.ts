// Generates src/api/schema.gen.ts and src/api/moments.gen.ts from the backend's OpenAPI document
// (frontend.md §5.2). Moments (`format: bigint`) are typed `MomentString`, and moments.gen.ts says
// where they sit in each schema so the data layer can turn them into `bigint`.
//   node scripts/gen-api.ts           write the file (`make gen`)
//   node scripts/gen-api.ts --check   fail if the committed file is stale (`make check-contract`)
import { execFileSync, spawnSync } from 'node:child_process'
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

import openapiTS, { astToString, type OpenAPI3, type SchemaObject } from 'openapi-typescript'
import ts from 'typescript'

const frontendDir = fileURLToPath(new URL('..', import.meta.url))
const backendDir = path.resolve(frontendDir, '../backend')
const target = path.join(frontendDir, 'src/api/schema.gen.ts')
const momentsTarget = path.join(frontendDir, 'src/api/moments.gen.ts')

const HEADER = `// Generated by \`make gen\` (frontend/scripts/gen-api.ts) from the backend's OpenAPI document.
// Do not edit by hand: change the backend models, then run \`make gen\` and commit this file.

`

type Shape =
  'm' | { a: Shape } | { d: Shape } | { o: Record<string, Shape> } | { r: string } | { u: Shape[] }

type Schema = SchemaObject & {
  $ref?: string
  properties?: Record<string, Schema>
  additionalProperties?: boolean | Schema
}

const REF_PREFIX = '#/components/schemas/'

function isMoment(schema: Schema): boolean {
  return schema.format === 'bigint' && schema.type === 'string'
}

/** Where moments sit in a schema; `null` when nowhere. `withMoments` holds the schema names that
 * (transitively) contain moments. */
function shapeOf(schema: Schema, withMoments: Set<string>): Shape | null {
  if (schema.$ref !== undefined) {
    const name = schema.$ref.slice(REF_PREFIX.length)
    return withMoments.has(name) ? { r: name } : null
  }
  if (isMoment(schema)) return 'm'
  const shapes: Shape[] = []
  for (const key of ['anyOf', 'oneOf', 'allOf'] as const) {
    for (const sub of (schema[key as keyof Schema] as Schema[] | undefined) ?? []) {
      const found = shapeOf(sub, withMoments)
      if (found !== null) shapes.push(found)
    }
  }
  if ('items' in schema && schema.items !== undefined) {
    const items = shapeOf(schema.items as Schema, withMoments)
    if (items !== null) shapes.push({ a: items })
  }
  const props: Record<string, Shape> = {}
  for (const [key, sub] of Object.entries(schema.properties ?? {})) {
    const found = shapeOf(sub, withMoments)
    if (found !== null) props[key] = found
  }
  if (Object.keys(props).length > 0) shapes.push({ o: props })
  const extra = schema.additionalProperties
  if (typeof extra === 'object') {
    const found = shapeOf(extra, withMoments)
    if (found !== null) shapes.push({ d: found })
  }
  const [only] = shapes
  if (only === undefined) return null
  return shapes.length === 1 ? only : { u: shapes }
}

/** The schema names whose instances can hold moments: a fixpoint over `$ref`s. */
function schemasWithMoments(schemas: Record<string, Schema>): Set<string> {
  const found = new Set<string>()
  for (;;) {
    const before = found.size
    for (const [name, schema] of Object.entries(schemas)) {
      if (!found.has(name) && shapeOf(schema, found) !== null) found.add(name)
    }
    if (found.size === before) return found
  }
}

function momentShapes(document: OpenAPI3): string {
  const schemas = (document.components?.schemas ?? {}) as Record<string, Schema>
  const withMoments = schemasWithMoments(schemas)
  const shapes = Object.fromEntries(
    Object.entries(schemas)
      .filter(([name]) => withMoments.has(name))
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([name, schema]) => [name, shapeOf(schema, withMoments)]),
  )
  return `${HEADER}import type { MomentShape } from './moment'

/** Where moments sit in each API schema that holds any (\`MomentShape\`). */
export const MOMENT_SHAPES: Readonly<Record<string, MomentShape>> = ${JSON.stringify(shapes, null, 2)}
`
}

const momentType = ts.factory.createTypeReferenceNode('MomentString')

async function generate(): Promise<{ schema: string; moments: string }> {
  const tmp = mkdtempSync(path.join(tmpdir(), 'lore-openapi-'))
  try {
    const document = path.join(tmp, 'openapi.json')
    execFileSync('uv', ['run', '--quiet', 'lore', 'openapi', '--out', document], {
      cwd: backendDir,
      stdio: 'inherit',
    })
    const ast = await openapiTS(pathToFileURL(document), {
      inject: "import type { MomentString } from './moment'\n",
      // Properties with a default are optional (as in the OpenAPI document): a PATCH body must not
      // have to send them.
      defaultNonNullable: false,
      transform: (schema) => (isMoment(schema as Schema) ? momentType : undefined),
    })
    const parsed = JSON.parse(readFileSync(document, 'utf8')) as OpenAPI3
    return { schema: HEADER + astToString(ast), moments: momentShapes(parsed) }
  } finally {
    rmSync(tmp, { recursive: true, force: true })
  }
}

function check(file: string, generated: string): boolean {
  const relative = path.relative(process.cwd(), file)
  const committed = existsSync(file) ? readFileSync(file, 'utf8') : null
  if (committed === generated) return true

  console.error(
    `${relative} is out of date with the backend's OpenAPI document.\n` +
      'Run `make gen` and commit the result (never edit generated files by hand).\n',
  )
  if (committed !== null) {
    const tmp = mkdtempSync(path.join(tmpdir(), 'lore-openapi-'))
    try {
      const fresh = path.join(tmp, path.basename(file))
      writeFileSync(fresh, generated)
      spawnSync('git', ['--no-pager', 'diff', '--no-index', '--stat', '--', file, fresh], {
        stdio: 'inherit',
      })
    } finally {
      rmSync(tmp, { recursive: true, force: true })
    }
  }
  return false
}

const { schema, moments } = await generate()
const outputs: [string, string][] = [
  [target, schema],
  [momentsTarget, moments],
]
if (process.argv.includes('--check')) {
  const stale = outputs.filter(([file, generated]) => !check(file, generated))
  if (stale.length > 0) process.exit(1)
  for (const [file] of outputs) console.log(`${path.relative(process.cwd(), file)} is up to date.`)
} else {
  for (const [file, generated] of outputs) {
    writeFileSync(file, generated)
    console.log(`wrote ${path.relative(process.cwd(), file)}`)
  }
}
